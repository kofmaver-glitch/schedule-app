"""
Разбор содержимого одной ячейки Word-таблицы.
Например: 'ВБ 20' → код='вб', аудитория='20', тип='лекция'
"""

import re


def parse_cell(text: str) -> dict | None:
    """
    Разбирает текст ячейки.
    Возвращает словарь или None, если ячейка пустая.
    """
    text = text.strip()
    
    # Пустая ячейка — пропускаем
    if not text or text in ("", " ", "\xa0"):
        return None
    
    # Проверка на жирный шрифт (зачёт/экзамен) — передаётся снаружи, 
    # здесь не можем определить (нужно смотреть на run.bold)
    
    # Определяем тип занятия
    # 1. пр(сп) — особая практика
    if text.lower() == "пр(сп)":
        return {
            "код": "пр(сп)",
            "аудитория": "",
            "тип": "практика",
            "дистант": False,
            "сырой_текст": text,
        }
    
    # 2. Дистант: ПА-д
    if text.endswith("-д"):
        base = text[:-2].strip()
        return _parse_basic(base, дистант=True, сырой_текст=text)
    
    # 3. Лекция в классе кафедры: ПА к
    if text.endswith(" к"):
        base = text[:-2].strip()
        return _parse_basic(base, аудитория="класс кафедры", сырой_текст=text)
    
    # 4. Обычная ячейка
    return _parse_basic(text, сырой_текст=text)


def _parse_basic(text: str, дистант: bool = False, 
                 аудитория: str = "", сырой_текст: str = "") -> dict:
    """
    Разбирает базовую ячейку: либо 'ВБ 20' (лекция), либо 'вб' (практика).
    """
    # Пробуем найти "КОД ЧИСЛО" — например, "ВБ 20"
    match = re.match(r"^([А-Яа-яЁё\-]+)\s+(\d+)$", text)
    if match:
        код = match.group(1).lower()
        ауд = match.group(2)
        return {
            "код": код,
            "аудитория": ауд,
            "тип": "лекция",
            "дистант": дистант,
            "сырой_текст": сырой_текст or text,
        }
    
    # Просто код строчными (практика): "вб"
    if re.match(r"^[а-яё\-]+$", text):
        return {
            "код": text.lower(),
            "аудитория": аудитория,
            "тип": "практика",
            "дистант": дистант,
            "сырой_текст": сырой_текст or text,
        }
    
    # Просто код заглавными без аудитории: "ВБ"
    if re.match(r"^[А-ЯЁ\-]+$", text):
        return {
            "код": text.lower(),
            "аудитория": аудитория,
            "тип": "лекция",
            "дистант": дистант,
            "сырой_текст": сырой_текст or text,
        }
    
    # Не распозналось — вернём как есть
    return {
        "код": text.lower(),
        "аудитория": аудитория,
        "тип": "неизвестно",
        "дистант": дистант,
        "сырой_текст": сырой_текст or text,
    }