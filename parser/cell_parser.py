"""
Разбор содержимого одной ячейки Word-таблицы.
Например: 'ВБ 20' → код='вб', аудитория='20', тип='лекция'
"""

import re


def parse_cell(text: str) -> dict | None:
    """
    Разбирает текст ячейки.
    Возвращает словарь или None, если ячейка пустая.
    """
    text = text.strip()
    
    # Пустая ячейка или прочерк — пропускаем
    if not text or text in ("", " ", "\xa0", "\\-", "-", "–"):
        return None
    
    # --- Дистанционные лекции и практики: "БЖ-д", "ТФ-д", "ЛП-д" ---
    if text.endswith("-д"):
        base = text[:-2].strip()
        # Определяем тип: заглавные = лекция, строчные = практика
        is_lecture = base.isupper()
        return {
            "код": base.lower(),
            "аудитория": "",
            "тип": "лекция" if is_lecture else "практика",
            "дистант": True,
            "сырой_текст": text,
        }
    
    # --- Лекция в классе кафедры: "ПА к" ---
    if text.endswith(" к"):
        base = text[:-2].strip()
        return _parse_basic(base, аудитория="класс кафедры", сырой_текст=text)
    
    # --- Особая практика: "пр(сп)", "пр(тп)", "пр(хп)" ---
    if text.lower().startswith("пр(") and text.endswith(")"):
        return {
            "код": text.lower(),
            "аудитория": "",
            "тип": "практика",
            "дистант": False,
            "сырой_текст": text,
        }
    
    # --- Обычная ячейка ---
    return _parse_basic(text, сырой_текст=text)


def _parse_basic(text: str, дистант: bool = False, 
                 аудитория: str = "", сырой_текст: str = "") -> dict:
    """
    Разбирает базовую ячейку: либо 'ВБ 20' (лекция), либо 'вб' (практика).
    """
    # Пробуем найти "КОД ЧИСЛО" — например, "ВБ 20"
    match = re.match(r"^([А-Яа-яЁё\-]+)\s+(\d+)$", text)
    if match:
        код = match.group(1).lower()
        ауд = match.group(2)
        return {
            "код": код,
            "аудитория": ауд,
            "тип": "лекция",
            "дистант": дистант,
            "сырой_текст": сырой_текст or text,
        }
    
    # Просто код строчными (практика): "вб"
    if re.match(r"^[а-яё\-()]+$", text):
        return {
            "код": text.lower(),
            "аудитория": аудитория,
            "тип": "практика",
            "дистант": дистант,
            "сырой_текст": сырой_текст or text,
        }
    
    # Просто код заглавными без аудитории: "ВБ"
    if re.match(r"^[А-ЯЁ\-]+$", text):
        return {
            "код": text.lower(),
            "аудитория": аудитория,
            "тип": "лекция",
            "дистант": дистант,
            "сырой_текст": сырой_текст or text,
        }
    
    # Не распозналось — вернём как есть
    return {
        "код": text.lower(),
        "аудитория": аудитория,
        "тип": "неизвестно",
        "дистант": дистант,
        "сырой_текст": сырой_текст or text,
    }